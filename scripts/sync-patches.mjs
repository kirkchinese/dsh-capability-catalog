#!/usr/bin/env node
// Generates the REA server row from packages/rea/families.yml and copies the bundle
// patches into the integration package, so every package carries the same rows.
// Usage: node scripts/sync-patches.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (path) => readFileSync(join(root, path), 'utf8')
const families = read('packages/rea/families.yml')
  .split('\n').filter((line) => !line.startsWith('#') && line.trim() !== '')
  .map((line) => `          ${line}`).join('\n')

const header = '# Generated by scripts/sync-patches.mjs from packages/rea/families.yml; edit that file instead.\n'
const reaRow = `${header}# REA through the capability catalog. Deprecated once REA ships tool groups upstream or the
# Harness DeepSeek adapter supports deferred tools; see packages/rea/README.md.
- insert:
    - id: capability-catalog-rea
      name: '@kirkchinese/dsh-capability-catalog/server'
      config:
        name: rea
        title: REA reverse engineering
        description: >-
          Reverse engineering of native binaries, JavaScript/Electron and web apps, Android, .NET,
          Apple bundles, firmware and runtime behavior, with evidence for every finding. For workflow
          guidance load the skill reverse-engineer-anything when it is available; tool names in it map
          to ids mcp:rea/<name>.
        command: rea
        args: [mcp]
        families:
${families}
`
const catalogRow = read('packages/capability-catalog/cordis.patch.yml')
const outputs = {
  'packages/rea/cordis.patch.yml': reaRow,
  'packages/re-kit/catalog.patch.yml': `${header}${catalogRow}`,
  'packages/re-kit/rea.patch.yml': reaRow,
}
const check = process.argv.includes('--check')
let stale = false
for (const [path, content] of Object.entries(outputs)) {
  let current = ''
  try { current = read(path) } catch {}
  if (current === content) continue
  if (check) { console.error(`stale: ${path}`); stale = true } else writeFileSync(join(root, path), content)
}
process.exit(stale ? 1 : 0)
